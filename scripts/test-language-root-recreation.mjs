import assert from "node:assert/strict";
import { build } from "esbuild";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const tempDir = await mkdtemp(join(tmpdir(), "conlang-root-recreation-"));

try {
  const outputFile = join(tempDir, "language-root-recreation.mjs");

  await build({
    entryPoints: ["language-root-recreation.ts"],
    bundle: true,
    platform: "node",
    format: "esm",
    outfile: outputFile,
    logLevel: "silent",
  });

  const { planLanguageRootRecreation } = await import(
    `${pathToFileURL(outputFile).href}?t=${Date.now()}`
  );

  const root = "Languages/Test Language";

  const expectedPaths = {
    root,
    lexicon: `${root}/Lexicon`,
    morphemes: `${root}/Morphemes`,
    inflections: `${root}/Inflections`,
    cyphers: `${root}/Cyphers`,
    examples: `${root}/Examples`,
    phonology: `${root}/Phonology`,
  };

  function makeLanguage(overrides = {}) {
    return {
      name: "Test Language",
      workbenchID: "wb:language:test-language",
      rootFolder: root,
      dictionaryFolder: expectedPaths.lexicon,
      morphemeFolder: expectedPaths.morphemes,
      exampleFolder: expectedPaths.examples,
      phonologyFolder: expectedPaths.phonology,
      sheets: [],
      hoverEnabled: true,
      ...overrides,
    };
  }

  /*
   * Recreate distinguishes the shared Languages container from the individual
   * configured root beneath it. Most planner regressions therefore model an
   * existing container while varying only the state of this language's root.
   */
  function makePathState(rootState, containerState = "folder") {
    return (path) => {
      if (path === "Languages") return containerState;
      if (path === root) return rootState;
      return "missing";
    };
  }

  /*
   * The normal recreation case is intentionally narrow: this exact configured
   * language still claims a valid root, no other configuration conflicts with
   * it, and the physical root remains absent.
   *
   * Planning is read-only. It identifies the only folder hierarchy a later
   * explicit transaction may establish.
   */
  {
    const language = makeLanguage();

    const result = planLanguageRootRecreation({
      language,
      languages: [language],
      pathState: makePathState("missing"),
    });

    assert.equal(result.status, "planned");
    assert.equal(result.root, root);
    assert.deepEqual(result.paths, expectedPaths);
    assert.deepEqual(result.foldersToEstablish, [
      expectedPaths.root,
      expectedPaths.lexicon,
      expectedPaths.morphemes,
      expectedPaths.inflections,
      expectedPaths.cyphers,
      expectedPaths.examples,
      expectedPaths.phonology,
    ]);

    /*
     * Recreate plans structural work only. Stable configured-language identity
     * is existing authority and must not be regenerated by planning.
     */
    assert.equal(language.workbenchID, "wb:language:test-language");
    assert.equal(language.rootFolder, root);
  }

  /*
   * Recreate may not infer or invent a root for a configuration that has no
   * established modern ownership boundary.
   */
  {
    const language = makeLanguage({
      rootFolder: undefined,
    });

    const result = planLanguageRootRecreation({
      language,
      languages: [language],
      pathState: () => "missing",
    });

    assert.equal(result.status, "blocked");
    assert.equal(result.reason, "root-unresolved");
  }

  /*
   * A malformed configured path is not repaired into another location. The
   * creator must resolve the authority problem explicitly.
   */
  {
    const language = makeLanguage({
      rootFolder: "Languages/Test Language/Nested",
    });

    const result = planLanguageRootRecreation({
      language,
      languages: [language],
      pathState: () => "missing",
    });

    assert.equal(result.status, "blocked");
    assert.equal(result.reason, "invalid-root");
  }

  /*
   * Another configured language's structural claim remains authoritative even
   * while the physical folder is absent. Recreate cannot use missing-on-disk
   * state to steal or merge ownership.
   */
  {
    const language = makeLanguage();

    const other = {
      name: "Other Language",
      rootFolder: root,
      dictionaryFolder: `${root}/Other Lexicon`,
      sheets: [],
      hoverEnabled: true,
    };

    const result = planLanguageRootRecreation({
      language,
      languages: [language, other],
      pathState: () => "missing",
    });

    assert.equal(result.status, "blocked");
    assert.equal(result.reason, "root-conflict");
    assert.match(result.detail, /Other Language/);
  }

  /*
   * Recreate may restore one configured language root, but it does not own the
   * shared Languages container. If that broader structure disappeared, the
   * creator must restore it before Recreate can establish anything beneath it.
   */
  {
    const language = makeLanguage();

    const result = planLanguageRootRecreation({
      language,
      languages: [language],
      pathState: makePathState("missing", "missing"),
    });

    assert.equal(result.status, "blocked");
    assert.equal(result.reason, "container-missing");
    assert.match(result.detail, /shared "Languages" folder is missing/i);
    assert.match(result.detail, /Restore it in the vault/i);
  }

  /*
   * A non-folder at the shared container path is an even stronger collision.
   * Recreate must never replace or reinterpret that creator-visible object.
   */
  {
    const language = makeLanguage();

    const result = planLanguageRootRecreation({
      language,
      languages: [language],
      pathState: makePathState("missing", "other"),
    });

    assert.equal(result.status, "blocked");
    assert.equal(result.reason, "container-not-folder");
    assert.match(result.detail, /not a folder/i);
    assert.match(result.detail, /will not replace or reinterpret/i);
  }

  /*
   * If a folder appears after the missing-root condition was observed,
   * recreation authority ends. Workbench does not silently adopt the newly
   * present folder and instead directs the creator back to ordinary Repair.
   */
  {
    const language = makeLanguage();

    const result = planLanguageRootRecreation({
      language,
      languages: [language],
      pathState: makePathState("folder"),
    });

    assert.equal(result.status, "blocked");
    assert.equal(result.reason, "root-now-folder");
    assert.match(result.detail, /folder now exists/i);
    assert.match(result.detail, /Repair language root/);
  }

  /*
   * A non-folder object occupying the configured root path is a hard stop.
   * Neither Recreate nor Repair is allowed to replace or reinterpret it.
   */
  {
    const language = makeLanguage();

    const result = planLanguageRootRecreation({
      language,
      languages: [language],
      pathState: makePathState("other"),
    });

    assert.equal(result.status, "blocked");
    assert.equal(result.reason, "root-not-folder");
    assert.match(result.detail, /will not replace or reinterpret/i);
    assert.doesNotMatch(result.detail, /try Repair language root/i);
  }

  console.log("language root recreation planner regression tests passed");
} finally {
  await rm(tempDir, { recursive: true, force: true });
}
